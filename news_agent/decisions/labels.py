def normalise_label(raw) -> str:
    """Привести метку к строке: `0` и `"0"` — одно и то же.

    В YAML `label: 0` без кавычек — это ЦЕЛОЕ, а `label: "0"` — строка; разметка должна приниматься в
    обеих формах, иначе половина набора молча выпала бы как «не размечено». `bool` отсекается: в
    Python это подкласс `int`, и `label: true` дал бы «1».
    """
    if raw is None or isinstance(raw, bool):
        return ""
    return str(raw).strip()


def expected_answer(label: str) -> str:
    """Какой ответ решателя считается верным для этой метки («да»/«нет» — язык вариантов гейта)."""
    return "да" if label == LABEL_SHOW else "нет"


def carry_labels(previous: list[dict], current: list[dict], *, reset: bool = False) -> list[dict]:
    """Перенести метки из ПРЕЖНЕЙ версии набора в новую по совпадению адреса или заголовка.

    **Зачем отдельная функция.** Сборщик набора накопительный: он добавляет найденное к уже
    собранному и перезаписывает файл. Сборщик, пишущий всем пустую метку, стирает разметку
    владельца одним запуском — а на ней стоят все числа. Правило
    живёт здесь, рядом со словарём меток, потому что это правило меток, а не свойство конкретного
    скрипта; `reset=True` — явное решение стереть, чтобы потеря не была следствием случайного запуска.
    """
    if reset:
        return [{**item, "label": ""} for item in current]
    known: dict[str, str] = {}
    for item in previous:
        label = normalise_label(item.get("label"))
        if not label:
            continue
        for key in (str(item.get("url") or "").strip(), str(item.get("title") or "").strip()):
            if key:
                known[key] = label
    carried = []
    for item in current:
        label = normalise_label(item.get("label"))
        if not label:
            for key in (str(item.get("url") or "").strip(), str(item.get("title") or "").strip()):
                if key and key in known:
                    label = known[key]
                    break
        carried.append({**item, "label": label})
    return carried
