"""Три роли команды: описания, а не агенты.

Роли — это данные: цель, вход, ожидаемый выход и какие инструменты роли даны. Собирает из них
агентов фреймворк. Здесь нет ни одного импорта
CrewAI, поэтому состав команды проверяется тестом без установки фреймворка.

Состав задан спецификацией пункта: **исследователь → автор → проверяющий факты**. Порядок
передачи результата — тоже часть спецификации, и он же порядок кортежа `ROLES`.
"""
from __future__ import annotations

from dataclasses import dataclass

from news_agent.news_team.tools import BY_NAME

RESEARCHER = "researcher"
AUTHOR = "author"
VERIFIER = "verifier"


@dataclass(frozen=True)
class Role:
    """Роль команды. `tools` — имена из реестра инструментов, а не модули."""

    key: str
    title: str
    goal: str
    expected: str
    tools: tuple[str, ...] = ()
    # Пользуется ли роль инструментами, подключёнными по MCP. Признак живёт здесь, а не в
    # сборке: раздача инструментов — это описание роли, и она должна быть видна без фреймворка.
    uses_mcp: bool = False


ROLES: tuple[Role, ...] = (
    Role(
        key=RESEARCHER,
        title="Исследователь",
        goal="Найти материал по теме новости, опираясь на инструменты, а не на память модели.",
        expected="Список найденных новостей в формате NEWS|{json}, по строке на новость.",
        # Поиск по базе знаний — наш инструмент; инструменты для поиска НОВОСТЕЙ приходят по
        # MCP: новости живут в интернете, а не в статьях о сделках.
        tools=(BY_NAME["knowledge_search"].NAME,),
        uses_mcp=True,
    ),
    Role(
        key=AUTHOR,
        title="Автор",
        goal="Переписать черновик так, чтобы он читался как заметка агентства, не теряя фактов.",
        expected="Текст заметки без служебных строк.",
    ),
    Role(
        key=VERIFIER,
        title="Проверяющий факты",
        goal=("Проверить инструментом, не потерялись ли факты, и учесть исход гейта новости: он "
              "приходит в задании. По теме ли новость и нет ли признаков рекламы решает ЛОКАЛЬНЫЙ "
              "РЕШАТЕЛЬ до тебя, а применяет решение мост."),
        expected=("Строка VERDICT| с итоговым текстом и перечнем потерянных фактов; в поле show — "
                  "показывать ли новость владельцу (исход гейта придёт в задании)."),
        # ОДИН инструмент — `lost_facts` (первый уровень лестницы, детерминированный).
        # Гейт новости (второй уровень) роли ИНСТРУМЕНТОМ НЕ ДАЁТСЯ намеренно: иначе открыт путь
        # скрыть новость в обход лестницы — роль вызывает гейт сама и ставит `show:false`,
        # а когда наш вызов деградировал, её слово подхватывалось как решение (`news_gate.apply`), и
        # новость пряталась при записи «решателя нет». Исход гейта передаётся роли ДАННЫМИ в задании
        # (`run.py`), и применяет его наш код — роль не может ни спросить гейт заново, ни решить за него.
        tools=(BY_NAME["lost_facts"].NAME,),
    ),
)

BY_KEY = {role.key: role for role in ROLES}


def role(key: str) -> Role:
    """Роль по ключу. Неизвестный ключ — ошибка программиста, а не пользователя."""
    try:
        return BY_KEY[key]
    except KeyError as error:
        raise ValueError(f"неизвестная роль команды: {key!r}") from error
