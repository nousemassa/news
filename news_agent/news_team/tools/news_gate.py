"""Инструмент «гейт новости»: стоит ли показывать новость владельцу.

Второй инструмент проверяющего — рядом с детерминированным `lost_facts`. Первый отвечает на вопрос
«не потерялись ли факты», второй — «по теме ли новость и нет ли признаков рекламы». Спрашивает
**локальный решатель** (`agent_core.decisions`), поэтому стоит около секунды и ничего не тратит на облако.

**Почему решение применяет наш код, а не формулировка роли.** Документы пункта называют это красным
флагом: «применяет решение всё равно мост». Поэтому `run_once` сам спрашивает гейт и кладёт его
исход в `Run`, а роль получает тот же исход данными и инструментом. Роль не может «показать» то,
что гейт уверенно отклонил: показ решает наш код по видимому уровню лестницы.

**Вопрос и варианты живут здесь одни на двух потребителей** — инструмента и замера
(`news_agent.decisions.report`). Разойдись они, точность измерялась бы на другом вопросе, чем тот,
который задаётся в проде (тот же принцип, что у `_has_prose` в чистке корпуса и в отчёте о корпусе).

**Деградация:** решателя нет — инструмент говорит это словами, гейт остаётся открытым (показываем),
и роль решает сама. Молча закрыть новость при сбое нельзя: «не знаю» — не «нет».
"""
from __future__ import annotations

from collections.abc import Awaitable, Callable

from agent_core.decisions.client import Decision, SolverBadAnswer, SolverUnavailable
from agent_core.decisions.ladder import (
    LEVEL_SOLVER,
    REASON_UNAVAILABLE,
    Step,
    choose,
)

NAME = "news_gate"

DESCRIPTION = (
    "Проверить, стоит ли показывать новость владельцу агентства: по теме ли она и нет ли признаков "
    "рекламы. Отвечает локальный решатель с оценкой уверенности; при низкой уверенности решение "
    "остаётся за тобой."
)

# Формулировка вопроса — одна на инструмент и на замер (см. докстроку модуля).
QUESTION = "Стоит ли показать эту новость владельцу агентства недвижимости?"
OPTIONS = {
    "да": "новость по теме рынка недвижимости и без признаков рекламы",
    "нет": "новость не по теме ИЛИ содержит признаки рекламы",
}

# Ответ, при котором новость НЕ показывается. Константа, а не литерал по месту: значение сверяется
# и в решении, и в отчёте, и в тестах.
REJECT_ANSWER = "нет"

# Функция «спросить решателя» — то, чем инструмент пользуется. В проде это клиент `solver`, в тестах
# двойник; поэтому модуль проверяется без сети.
AskSolver = Callable[[str, str, dict[str, str]], Awaitable[Decision]]


async def judge(text: str, *, ask: AskSolver, threshold: float) -> tuple[Step, Decision | None]:
    """Спросить гейт и вернуть ДВА взгляда: шаг лестницы и сам ответ решателя.

    Зачем оба. Лестница намеренно не переносит ответ в уход на уровень 3 (`answer` непустой только у
    закрытого локально случая) — иначе «закрыто локально» потеряло бы однозначность. Но замеру нужен
    и сам ответ: без него «точность решателя» считалась бы по уходам как по ошибкам, а это неправда —
    уход это решение «спросить облако», а не неверный ответ. Проверено на данных: при росте порога
    такая метрика падала, хотя решатель не менялся.

    Никогда не бросает: сбой решателя — это шаг на уровень 3, а не падение прогона.
    """
    try:
        decision = await ask(text, QUESTION, OPTIONS)
    except (SolverUnavailable, SolverBadAnswer):
        # Деградация ловит ТОЛЬКО названные сбои сервиса: клиент уже упаковал в них сеть, таймаут и
        # битый ответ. Ловить здесь `Exception` нельзя: это прячет программные ошибки — опечатка в
        # двойнике выглядит как «решатель недоступен», и причину приходится искать по журналу.
        return choose(None, threshold=threshold, problem=REASON_UNAVAILABLE), None
    return choose(decision, threshold=threshold), decision


async def ask_gate(text: str, *, ask: AskSolver, threshold: float) -> Step:
    """Шаг лестницы — то, чем пользуются прогон и роль (см. `judge` про второй взгляд)."""
    step, _decision = await judge(text, ask=ask, threshold=threshold)
    return step


def rejects(step: Step) -> bool:
    """Гейт уверенно отклоняет новость. Только это и закрывает показ — и только ЛОКАЛЬНО.

    Неуверенный ответ не отклоняет: показ — состояние по умолчанию, и менять его на догадке нельзя.
    """
    return step.level == LEVEL_SOLVER and step.answer == REJECT_ANSWER


def format_for_model(step: Step) -> str:
    """Исход гейта словами — для роли и для журнала: видно, на каком уровне он закрыт.

    Язык намеренно описывает УРОВЕНЬ, а не только ответ: без этого «нет» от решателя и «нет» от
    облака выглядели бы одинаково, и экономию нельзя было бы посчитать.
    """
    head = f"Уровень лестницы: {step.level}. "
    if step.closed_locally:
        return (f"{head}Локальный решатель ответил «{step.answer}» с уверенностью "
                f"{step.confidence:.2f} (порог соблюдён) — облако не привлекалось.")
    return (f"{head}Локальный решатель не закрыл вопрос ({step.reason}, уверенность "
            f"{step.confidence:.2f}) — решение за тобой.")


def apply(step: Step, claimed_show: bool) -> bool:
    """Показывать ли выпуск — решение НАШЕГО кода, а не формулировки роли.

    Правило одно и названо явно: **уверенное локальное «нет» отменяет показ**, даже если роль
    написала `show: true`. Причина в том, что уровни лестницы не равны по цене: уверенное решение
    дешёвого уровня не перебивается текстом дорогого — иначе гейт был бы украшением.
    Во всех остальных случаях показываем то, что решила роль: неуверенность гейта и его отсутствие
    не должны скрывать новость от владельца.
    """
    if rejects(step):
        return False
    return claimed_show
