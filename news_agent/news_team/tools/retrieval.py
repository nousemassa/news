"""Инструмент «поиск по базе знаний»: ретривер базы знаний.

Роль-исследователь ищет материал инструментом, а не «из головы модели». Источник — та же база
знаний, что кормит диалог: одна реализация поиска на весь проект, второй копии не заводится
(иначе команда и диалог находили бы разное).
"""
from __future__ import annotations

import logging

log = logging.getLogger(__name__)

# Имя уходит в OpenAI-совместимый API как ИМЯ ФУНКЦИИ, поэтому оно ASCII: API принимает
# только `^[A-Za-z0-9_-]{1,64}$`, а на русском имени отвечает «function name cannot be empty»
# и команда падает. Закрыто тестом-охранником: структурная проверка раздачи инструментов такого
# не видит.
# Русским остаётся ОПИСАНИЕ: оно адресовано модели, а не API.
NAME = "knowledge_search"
DESCRIPTION = (
    "Найти фрагменты базы знаний агентства по вопросу. Возвращает тексты фрагментов. "
    "Если ничего не найдено — вернёт пустую строку, и это значит «данных нет», а не «ошибка»."
)


# Схема аргументов для OpenAI-совместимого вызова (см. `facts.py`).
SCHEMA = {
    "type": "object",
    "properties": {
        "query": {"type": "string", "description": "Вопрос, по которому ищем фрагменты базы знаний."},
        "limit": {"type": "integer", "description": "Сколько фрагментов вернуть (по умолчанию 4)."},
    },
    "required": ["query"],
}


async def search(retriever, query: str, *, limit: int = 4) -> str:
    """Тексты найденных фрагментов одной строкой. Пустая строка — «ничего не нашлось».

    Не бросает: недоступная база знаний означает «знаний нет», а не сломанный прогон команды.
    Причина пишется в журнал, чтобы пустой результат не выглядел как честное «не нашлось».
    """
    if retriever is None:
        return ""
    try:
        chunks = await retriever.search(query, limit=limit)
    except Exception as error:  # noqa: BLE001 — отказ инструмента не роняет прогон
        log.warning("news: поиск по базе знаний не удался (%s: %s)", type(error).__name__, error)
        return ""
    return "\n".join(chunk.text for chunk in chunks if getattr(chunk, "text", ""))
