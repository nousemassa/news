"""Инструмент «проверка фактов».

**Это обёртка, а не новая реализация.** Спецификация пункта запрещает переписывать проверку:
«`facts_kept` подключается инструментом проверяющего: остаётся тем же кодом». Причина
практическая — вторая реализация неизбежно разошлась бы с первой, и тогда команда и текущий
путь публикации судили бы о потере фактов по разным критериям.

Поэтому здесь только имя для модели и тонкий вызов `news.facts_kept`. Тест сравнивает
результат обёртки с прямым вызовом — это и есть защита от расхождения.
"""
from __future__ import annotations

from news_agent.news import facts_kept

# ASCII по той же причине, что у поиска: имя уходит в API как имя функции (см. retrieval.py).
NAME = "lost_facts"
DESCRIPTION = (
    "Проверить, потерял ли новый текст факты исходного (числа, проценты, даты). "
    "Возвращает список потерянных фактов; пустой список — потерь нет."
)


# Схема аргументов для OpenAI-совместимого вызова: API ждёт JSON-схему, а не подпись функции.
# Лежит рядом с инструментом, а не в сборке: аргументы — часть описания инструмента.
SCHEMA = {
    "type": "object",
    "properties": {
        "original": {"type": "string", "description": "Исходный текст, относительно которого проверяем."},
        "new_text": {"type": "string", "description": "Новый текст, в котором ищем потери."},
    },
    "required": ["original", "new_text"],
}


def missing_facts(original: str, new_text: str) -> list[str]:
    """Потерянные факты. Ничего не решает и не меняет — только сообщает."""
    return list(facts_kept(original, new_text))
