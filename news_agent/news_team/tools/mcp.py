"""Источники инструментов по MCP для команды. Разбор адресов, без фреймворка и сети.

**Почему MCP, а не Composio.** Composio рассматривался как кандидат (поверхность API изучена) и
отклонён в пользу бесплатного пути. Выбранный механизм инструментов — **MCP**: платформа отдаёт
инструменты через свой MCP-шлюз, встроенный набор инструментов в сборке платформы выключен. Поэтому и
инструменты команды приходят по MCP.

**Что здесь есть, а чего нет.** Здесь только **разбор и проверка адресов** — чистые функции без
сети. Само подключение делает адаптер фреймворка. Свой MCP-клиент здесь не нужен: клиентская часть
`fastmcp` в окружении **не установлена** — серверная есть, клиентская требует отдельного extra и
конфликтует версиями с `mcp`. Модуль живёт отдельно,
чтобы разбор источников проверялся тестом без фреймворка.
"""
from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from urllib.parse import urlparse

log = logging.getLogger(__name__)

# Разумный потолок на число источников: список источников инструментов — решение человека,
# а не то, что должно расти само. Больше пяти серверов на одну роль — это уже свалка.
MAX_SERVERS = 5

# Правило OpenAI-совместимого API для ИМЕНИ ФУНКЦИИ. Оно же решает судьбу MCP-инструментов:
# адаптер фреймворка составляет имя как `<префикс сервера>_<имя инструмента>`, префикс берёт из
# АДРЕСА (правило своё, зеркалит адаптер фреймворка: `_extract_server_name` →
# `netloc.replace(".", "_")`): потом санитайз выкидывает не-ASCII,
# приводит к нижнему регистру, заменяет недопустимые символы на `_`, схлопывает их и режет до 64.
#
# Отсюда ДВА дефекта одного класса, которые надо закрыть до вызова API:
#   1) русское имя инструмента санитайзер вырезает в ПУСТОЕ имя — «function name cannot be empty»;
#   2) адрес по IP даёт префикс, НАЧИНАЮЩИЙСЯ С ЦИФРЫ, и API отвечает «must start with a letter or
#      underscore» — при этом сам санитайзер ведущую цифру НЕ лечит.
FUNCTION_NAME_RE = re.compile(r"[a-z_][a-z0-9_]{0,63}\Z")

# Длина имени инструмента по правилу API: длиннее обрежет санитайзер, и имена могут совпасть.
MAX_FUNCTION_NAME = 64


@dataclass(frozen=True)
class McpServer:
    """Источник инструментов: адрес и (необязательно) имя для журнала."""

    url: str
    name: str = ""


def tool_name_prefix(url: str) -> str:
    """Префикс имён инструментов этого сервера — как его считает адаптер фреймворка.

    Повторяем правило у себя сознательно: без него нельзя ПРОВЕРИТЬ адрес до подключения, а
    значит нельзя закрыть охранником дефект, который иначе находится платным прогоном.
    """
    parsed = urlparse(url)
    domain = parsed.netloc.replace(".", "_")
    path = parsed.path.replace("/", "_").strip("_")
    return f"{domain}_{path}" if path else domain


def sanitized_name(name: str) -> str:
    """Имя так, как его приведёт санитайзер фреймворка (порядок шагов важен).

    Не-ASCII выкидывается (и именно поэтому русские имена инструментов доходили пустыми), затем
    недопустимые символы становятся `_`, повторы схлопываются, имя режется до 64.
    """
    name = name.encode("ascii", "ignore").decode("ascii")
    name = re.sub(r"[^A-Za-z0-9]+", "_", name).lower()
    return re.sub(r"_+", "_", name).strip("_")[:MAX_FUNCTION_NAME]


def final_tool_name(url: str, tool: str = "searxng_web_search") -> str:
    """Имя инструмента, которое уйдёт в API: префикс сервера + имя инструмента, санитизированное.

    `tool` по умолчанию — реальное имя инструмента searxng: проверять правило на выдуманном имени
    значило бы проверять не то, что случится на живом сервере.
    """
    return sanitized_name(f"{tool_name_prefix(url)}_{tool}")


def address_problem(url: str) -> str:
    """Почему адрес негоден для инструментов команды. Пустая строка — годен.

    Проверяется не «вежливость формата», а то, что имя инструмента дойдёт до модели: API
    принимает только `^[a-z_][a-z0-9_]{0,63}$` уже ПОСЛЕ санитайзера, а первый символ имени
    берётся из адреса.
    """
    parsed = urlparse(url)
    if parsed.scheme not in ("http", "https") or not parsed.netloc:
        return "нужен адрес вида http(s)://хост:порт/путь"
    name = final_tool_name(url)
    if not FUNCTION_NAME_RE.fullmatch(name):
        return (
            f"адрес {url!r} даёт имя инструмента «{name}», а оно не проходит как имя функции в API "
            f"(правило {FUNCTION_NAME_RE.pattern}); адрес по IP начинается с цифры — укажите хост "
            f"по имени, например http://localhost:3000/mcp"
        )
    return ""


def parse_servers(raw: str) -> tuple[McpServer, ...]:
    """Разобрать список адресов MCP-серверов из настройки.

    Формат: адреса через запятую; имя можно дать как `имя=адрес`. Негодный адрес **пропускается,
    но с записью в журнал**: молча выброшенный источник — это тихо отключённая функция (у неё
    после этого нет никакого внешнего признака), а проект такие дефекты считает худшими. Причина
    называется словами, а не «неверный формат».

    Пустая строка ⇒ пустой кортеж: MCP-инструментов нет, и это нормальное состояние —
    команда работает со своими инструментами (деградация, как везде в проекте).
    """
    servers: list[McpServer] = []
    for chunk in (raw or "").split(","):
        item = chunk.strip()
        if not item:
            continue
        name, _, url = item.partition("=")
        if not url:
            name, url = "", name
        url = url.strip().rstrip("/")
        problem = address_problem(url)
        if problem:
            log.warning("news: MCP-сервер пропущен — %s", problem)
            continue
        servers.append(McpServer(url=url, name=name.strip()))
        if len(servers) >= MAX_SERVERS:
            break
    return tuple(servers)


# **Почему адресов в коде нет.** Записанные литералами адреса (`localhost:8087`,
# `localhost:3000`) расходятся с фактом сразу в двух местах: поиск живёт на своём порту, а в
# контейнере `localhost` не даёт ни листенера, ни поиска — там нужны имена сервисов docker-сети.
# Адрес ровно один и живёт в настройке
# (`TEAM_MCP_SERVERS` в `.env`), потому что от места запуска зависит.
#
# Своего поиска новостей у моста нет: он живёт отдельным сервисом. Поэтому без внешнего
# источника роль исследователя ищет новости в базе знаний агентства — то есть не ищет их вовсе.
# **Адреса — по имени, а не по IP**: префикс имени инструмента берётся из адреса, а IP начинается
# с цифры (см. `address_problem`).
