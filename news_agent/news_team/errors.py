"""Ошибка команды ролей: отдельный тип, а не общая ошибка.

**Зачем отдельный тип.** Вызывающий обязан **уйти на одиночный путь**, а не показать сбой: команда
не заменяет публикацию, она её ускоряет. Поэтому любая неисправность команды — недоступный
провайдер, пустой ответ модели, превышенный цикл инструментов, упавший шаг — приводится к одному
типу, по которому вызывающий принимает решение. Показать клиенту техническую ошибку вместо новости
нельзя, и «почти получилось» тоже нельзя.
"""
from __future__ import annotations


class TeamUnavailable(RuntimeError):
    """Команду ролей поднять или довести до результата нельзя — идём одиночным путём.

    **Почему ошибка несёт расход.** Провал шага тоже стоит денег: роль успевает выбрать все круги
    инструментов и падает, а измеритель без этих чисел показывает `$0,0000`, то есть «бесплатно».
    Ноль вместо израсходованного — та же ложь, что ноль вместо неизвестной цены. Поэтому расход идёт
    вместе с ошибкой.
    """

    def __init__(self, message: str, *, tokens: int = 0, cost_usd: float | None = None) -> None:
        super().__init__(message)
        self.tokens = tokens
        self.cost_usd = cost_usd
